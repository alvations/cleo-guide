'use strict';
/**
 * sw.js template — the beta service worker (offline city packs). Generated so the cache name carries the
 * build's asset hash: a new build retires old caches on activate.
 *   - precache: the shell (landing, saved, CSS, JS, icon, manifest);
 *   - navigations: network-first, fall back to the cached copy, then redirect to the cached landing page;
 *   - versioned assets (?v=…): cache-first;  data/*.json: stale-while-revalidate;
 *   - cross-origin requests (map tiles, source links): never intercepted. Tile caching is deferred —
 *     the OSM tile policy forbids bulk prefetch, and the list never needs tiles (offline, the map falls back to
 *     the build-time schematic of verified pins).
 *   - message {type:'cache', urls}: the page asks to keep itself + everything it loaded (core.js sends this once
 *     the worker is active, because the FIRST page of a visit was fetched before the worker controlled it), and
 *     "Save this city for offline" (Cleo.offline.save) sends the same. Same-origin, in-scope URLs only.
 */
function swSource(version, shell) {
  return `/* Cleo beta service worker — generated by tools/beta/build.js; do not edit. */
'use strict';
var V = 'cleo-${version}';
var SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(V).then(function (c) { return c.addAll(SHELL); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (ks) {
    return Promise.all(ks.filter(function (k) { return k.indexOf('cleo-') === 0 && k !== V; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
self.addEventListener('message', function (e) {
  var d = e.data || {}; if (d.type !== 'cache' || !d.urls || !d.urls.length) return;
  var scope = self.registration.scope, urls = d.urls.filter(function (u) { return typeof u === 'string' && u.indexOf(scope) === 0; })
    .map(function (u) { return u.split('#')[0]; });
  e.waitUntil(caches.open(V).then(function (c) {
    return Promise.all(urls.map(function (u) { return c.match(u).then(function (m) { return m || c.add(u).then(function () { return 1; }, function () { return 0; }); }); }));
  }).then(function (r) { if (e.source && e.source.postMessage) e.source.postMessage({ type: 'cached', n: r.length, ok: r.filter(Boolean).length }); }));
});
function put(req, res) { if (res && res.ok) { var copy = res.clone(); caches.open(V).then(function (c) { c.put(req, copy); }); } return res; }
self.addEventListener('fetch', function (e) {
  var req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(function (r) { return put(req, r); }).catch(function () {
      // a page never visited (so never cached): send the visitor to the cached landing at ITS OWN URL, so relative
      // links and styles resolve (serving the landing's bytes at /cities/x.html would break both)
      return caches.match(req, { ignoreSearch: true }).then(function (m) { return m || Response.redirect(new URL('./index.html', self.registration.scope).href, 302); });
    }));
    return;
  }
  if (/\\/data\\/[^/]+\\.json$/.test(url.pathname) || /\\/data\\/(places|links)\\//.test(url.pathname)) {
    e.respondWith(caches.match(req).then(function (m) {
      var net = fetch(req).then(function (r) { return put(req, r); }).catch(function () { return m; });
      return m || net;
    }));
    return;
  }
  e.respondWith(caches.match(req).then(function (m) { return m || fetch(req).then(function (r) { return put(req, r); }); }));
});
`;
}
module.exports = { swSource };
