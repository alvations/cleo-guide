'use strict';
/**
 * sw.js template — the beta service worker (offline city packs). Generated so the cache name carries the
 * build's asset hash: a new build retires old caches on activate.
 *   - precache: the shell (landing, saved, CSS, JS, icon, manifest);
 *   - navigations: network-first, fall back to the cached copy, then to the landing page;
 *   - versioned assets (?v=…): cache-first;  data/*.json: stale-while-revalidate;
 *   - cross-origin requests (map tiles, source links): never intercepted. Tile caching is deferred —
 *     the OSM tile policy forbids bulk prefetch, and the list never needs tiles.
 */
function swSource(version, shell) {
  return `/* Cleo beta service worker — generated by tools/beta/build.js; do not edit. */
'use strict';
var V = 'cleo-${version}';
var SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(V).then(function (c) { return c.addAll(SHELL); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (ks) {
    return Promise.all(ks.filter(function (k) { return k.indexOf('cleo-') === 0 && k !== V; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
function put(req, res) { if (res && res.ok) { var copy = res.clone(); caches.open(V).then(function (c) { c.put(req, copy); }); } return res; }
self.addEventListener('fetch', function (e) {
  var req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(function (r) { return put(req, r); }).catch(function () {
      return caches.match(req, { ignoreSearch: true }).then(function (m) { return m || caches.match('./index.html'); });
    }));
    return;
  }
  if (/\\/data\\/[^/]+\\.json$/.test(url.pathname) || /\\/data\\/places\\//.test(url.pathname)) {
    e.respondWith(caches.match(req).then(function (m) {
      var net = fetch(req).then(function (r) { return put(req, r); }).catch(function () { return m; });
      return m || net;
    }));
    return;
  }
  e.respondWith(caches.match(req).then(function (m) { return m || fetch(req).then(function (r) { return put(req, r); }); }));
});
`;
}
module.exports = { swSource };
