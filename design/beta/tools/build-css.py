#!/usr/bin/env python3
"""Assemble beta/assets/cleo.css — the ONE stylesheet every generated beta page links (after tokens.css).
    cleo.css = beta/assets/constellation.css (component library, UX-20)
             + design/beta/css/contract.css (RFC §5.5 markup adapter + the M1 visual layer: glyphs, covers, skins, type)
Edit those sources, never cleo.css. Then `cd tools && npm run beta` re-versions the CSS in every page.
    python3 design/beta/tools/build-css.py [--check]"""
import os, sys
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
lib = open(os.path.join(R, 'beta', 'assets', 'constellation.css')).read()
con = open(os.path.join(R, 'design', 'beta', 'css', 'contract.css')).read()
out = ('/* cleo.css — GENERATED by design/beta/tools/build-css.py — do not edit. Owner: UI/UX lane.\n'
       ' * Sources: beta/assets/constellation.css (components) + design/beta/css/contract.css (markup contract + M1 visuals).\n'
       ' * Requires beta/assets/tokens.css first. Fonts: beta/assets/fonts (OFL, self-hosted). */\n\n' + lib.rstrip() + '\n\n' + con)
# guards: no network-loaded resources, no forbidden tile hosts, no brand names in CSS
bad = [w for w in ('http://', 'https://fonts.', '@import', 'cartocdn', 'googleapis', 'gstatic') if w in out.replace("http://www.w3.org/2000/svg", '')]
if bad: sys.exit(f'build-css: refusing — found {bad}')
P = os.path.join(R, 'beta', 'assets', 'cleo.css')
if '--check' in sys.argv:
    ok = open(P).read() == out; print('build-css:', 'cleo.css in sync' if ok else 'cleo.css OUT OF DATE — run python3 design/beta/tools/build-css.py'); sys.exit(0 if ok else 1)
open(P, 'w').write(out); print(f'build-css: wrote beta/assets/cleo.css ({len(out.encode())/1024:.1f} KB)')
