#!/usr/bin/env python3
"""Assemble beta/assets/cleo.css — the ONE stylesheet every generated beta page links (after tokens.css).
    cleo.css = beta/assets/constellation.css (component library, UX-20)
             + design/beta/css/contract.css (RFC §5.5 markup adapter + the M1 visual layer: glyphs, covers, skins, type)
Edit those sources, never cleo.css. Then `cd tools && npm run beta` re-versions the CSS in every page.
    python3 design/beta/tools/build-css.py [--check]"""
import os, sys
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
lib = open(os.path.join(R, 'beta', 'assets', 'constellation.css')).read()
con = open(os.path.join(R, 'design', 'beta', 'css', 'contract.css')).read()
out = ('/* cleo.css — GENERATED by design/beta/tools/build-css.py — do not edit. Owner: UI/UX lane.\n'
       ' * Sources: beta/assets/constellation.css (components) + design/beta/css/contract.css (markup contract + M1 visuals).\n'
       ' * Requires beta/assets/tokens.css first. Fonts: beta/assets/fonts (OFL, self-hosted). */\n\n' + lib.rstrip() + '\n\n' + con)
# collection glyphs (D12): original line glyphs as CSS masks — .g[data-g] anywhere, and every .rail-i[data-c] tile
import json, re, urllib.parse
sys.path.insert(0, os.path.join(R, 'design', 'beta', 'tools'))
from svgkit import ICONS
NEW = {   # added W1, same 24-px grid, 1.75 stroke, round caps — generic, never a venue
  'wave':  '<path d="M2.5 8.5c2.4 0 2.4-2 4.75-2S9.6 8.5 12 8.5s2.4-2 4.75-2 2.35 2 4.75 2M2.5 13.5c2.4 0 2.4-2 4.75-2s2.35 2 4.75 2 2.4-2 4.75-2 2.35 2 4.75 2M2.5 18.5c2.4 0 2.4-2 4.75-2s2.35 2 4.75 2 2.4-2 4.75-2 2.35 2 4.75 2"/>',
  'train': '<rect x="5" y="3" width="14" height="14" rx="3"/><path d="M5 10h14M8.5 21l2-4M15.5 21l-2-4"/><circle cx="9" cy="13.5" r=".9"/><circle cx="15" cy="13.5" r=".9"/>',
  'flag':  '<path d="M5 21V3.5M5 4h12l-2.5 4L17 12H5"/>',
  'plane': '<path d="M21 4.5L3 11l7 2.5 2.5 7z"/><path d="M10 13.5l4-4"/>',
  'frame': '<rect x="3.5" y="4.5" width="17" height="15" rx="1"/><path d="M6.5 16.5l4-5 3 3.5 2-2.2 2 3.7"/><circle cx="15.5" cy="8.5" r="1.3"/>',
}
G = dict(ICONS, **NEW)
gcfg = json.load(open(os.path.join(R, 'design', 'beta', 'glyphs.json')))
used = sorted(set(gcfg['collections'].values()) | {'torii', 'star4', 'forkknife', 'route', 'pin', 'heart', 'day', 'compass', 'bowl', 'mountain', 'frame', 'columns'})   # W2: + UI glyphs for .mod/.leg/.pl-dist/.interest
def uri(body):
    svg = ("<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='%23000' stroke-width='1.75' "
           "stroke-linecap='round' stroke-linejoin='round'>" + body.replace('"', "'") + '</svg>')
    return 'url("data:image/svg+xml,' + urllib.parse.quote(svg, safe=" =:/'.,-%") + '")'
gl = ['/* ---------- collection glyphs (generated by build-css.py from svgkit.py ICONS + glyphs.json) ---------- */',
      ':root { ' + ' '.join(f'--g-{n}: {uri(G[n])};' for n in used) + ' }',
      '.g { display: inline-block; width: 22px; height: 22px; flex: none; background: currentColor; -webkit-mask: var(--g, var(--g-star4)) center / contain no-repeat; mask: var(--g, var(--g-star4)) center / contain no-repeat; }']
gl += [f'.g[data-g="{n}"] {{ --g: var(--g-{n}); }}' for n in used]
by = {}
for cid, n in gcfg['collections'].items(): by.setdefault(n, []).append(cid)
gl += [', '.join(f'.rail-i[data-c="{c}"]' for c in sorted(ids)) + f' {{ --g: var(--g-{n}); }}' for n, ids in sorted(by.items())]
gl.append(', '.join(f'main[data-city="{k}"] .rail-i[data-c="TEMPLE"]' for k in gcfg['japan']) + ' { --g: var(--g-torii); }')
gl.append('.rail-i[data-cz] { --g: var(--g-forkknife); }')
out += '\n' + '\n'.join(gl) + '\n'
# masthead art: one rule per city that has platform's verified-pin schematic (beta/assets/art/<key with / → -->/map.svg)
ART = os.path.join(R, 'beta', 'assets', 'art')
keys = sorted(d for d in (os.listdir(ART) if os.path.isdir(ART) else []) if os.path.exists(os.path.join(ART, d, 'map.svg')))
out += ('\n/* ---------- masthead art (generated by build-css.py from beta/assets/art/*/map.svg — platform lib/art.js) ---------- */\n'
        + '\n'.join(f'main[data-city="{k.replace("--", "/")}"] > .masthead::before, .dest[data-page="{k.replace("--", "/")}"] a:not(.tile)::after {{ background-image: url("art/{k}/map.svg"); }}' for k in keys) + '\n')
# guards: no network-loaded resources, no forbidden tile hosts, no brand names in CSS
bad = [w for w in ('http://', 'https://fonts.', '@import', 'cartocdn', 'googleapis', 'gstatic') if w in out.replace("http://www.w3.org/2000/svg", '')]
if bad: sys.exit(f'build-css: refusing — found {bad}')
P = os.path.join(R, 'beta', 'assets', 'cleo.css')
if '--check' in sys.argv:
    ok = open(P).read() == out; print('build-css:', 'cleo.css in sync' if ok else 'cleo.css OUT OF DATE — run python3 design/beta/tools/build-css.py'); sys.exit(0 if ok else 1)
open(P, 'w').write(out); print(f'build-css: wrote beta/assets/cleo.css ({len(out.encode())/1024:.1f} KB)')
